-- ============================================================================
-- A3 / DOC 03 - Validation 08/08: final reconciliation
-- Structure (18 tables, 22 logical foreign keys, 6066 real rows), the 8 A3
-- table volumes, 8 integrity rules with zero violations, and the
-- multicurrency readiness of plants 1200 and 2800.
-- Total records are counted with COUNT(*) - never SYS.M_TABLES.RECORD_COUNT,
-- which is a monitoring view and may lag the delta storage.
-- ============================================================================
SELECT * FROM (
    SELECT 1 AS SORT_ORDER, 'STRUCTURE' AS CHECK_ITEM, 'Tables in INDUSTRIAL_DATA' AS OBJECT_NAME,
           TO_NVARCHAR(COUNT(*)) AS ACTUAL_VALUE, '18' AS EXPECTED_VALUE,
           CASE WHEN COUNT(*) = 18 THEN 'PASSED' ELSE 'FAILED' END AS VALIDATION_STATUS
    FROM SYS.TABLES WHERE SCHEMA_NAME = 'INDUSTRIAL_DATA'
    UNION ALL
    SELECT 1, 'STRUCTURE', 'Logical foreign keys',
           TO_NVARCHAR(COUNT(DISTINCT TABLE_NAME || '.' || CONSTRAINT_NAME)), '22',
           CASE WHEN COUNT(DISTINCT TABLE_NAME || '.' || CONSTRAINT_NAME) = 22 THEN 'PASSED' ELSE 'FAILED' END
    FROM SYS.REFERENTIAL_CONSTRAINTS WHERE SCHEMA_NAME = 'INDUSTRIAL_DATA'
    UNION ALL
    SELECT 1, 'STRUCTURE', 'Total records (real row count)',
           TO_NVARCHAR(TOTAL_ROWS), '6066',
           CASE WHEN TOTAL_ROWS = 6066 THEN 'PASSED' ELSE 'FAILED' END
    FROM (
        SELECT (SELECT COUNT(*) FROM INDUSTRIAL_DATA.MATERIAL)
             + (SELECT COUNT(*) FROM INDUSTRIAL_DATA.PLANT)
             + (SELECT COUNT(*) FROM INDUSTRIAL_DATA.STORAGE_LOCATION)
             + (SELECT COUNT(*) FROM INDUSTRIAL_DATA.MATERIAL_PLANT)
             + (SELECT COUNT(*) FROM INDUSTRIAL_DATA.MATERIAL_STORAGE_LOCATION)
             + (SELECT COUNT(*) FROM INDUSTRIAL_DATA.COMPANY)
             + (SELECT COUNT(*) FROM INDUSTRIAL_DATA.COMPANY_CODE)
             + (SELECT COUNT(*) FROM INDUSTRIAL_DATA.PURCHASING_ORGANIZATION)
             + (SELECT COUNT(*) FROM INDUSTRIAL_DATA.PURCHASING_GROUP)
             + (SELECT COUNT(*) FROM INDUSTRIAL_DATA.PLANT_PURCHASING_ORG)
             + (SELECT COUNT(*) FROM INDUSTRIAL_DATA.MATERIAL_TYPE)
             + (SELECT COUNT(*) FROM INDUSTRIAL_DATA.MATERIAL_GROUP)
             + (SELECT COUNT(*) FROM INDUSTRIAL_DATA.UNIT_OF_MEASURE)
             + (SELECT COUNT(*) FROM INDUSTRIAL_DATA.DIVISION)
             + (SELECT COUNT(*) FROM INDUSTRIAL_DATA.CURRENCY)
             + (SELECT COUNT(*) FROM INDUSTRIAL_DATA.MATERIAL_DESCRIPTION)
             + (SELECT COUNT(*) FROM INDUSTRIAL_DATA.MATERIAL_VALUATION)
             + (SELECT COUNT(*) FROM INDUSTRIAL_DATA.MATERIAL_UOM) AS TOTAL_ROWS
        FROM DUMMY
    )
    UNION ALL
    SELECT 2, 'A3_VOLUME', 'MATERIAL_TYPE', TO_NVARCHAR(COUNT(*)), '4',
           CASE WHEN COUNT(*) = 4 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.MATERIAL_TYPE
    UNION ALL
    SELECT 2, 'A3_VOLUME', 'MATERIAL_GROUP', TO_NVARCHAR(COUNT(*)), '24',
           CASE WHEN COUNT(*) = 24 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.MATERIAL_GROUP
    UNION ALL
    SELECT 2, 'A3_VOLUME', 'UNIT_OF_MEASURE', TO_NVARCHAR(COUNT(*)), '6',
           CASE WHEN COUNT(*) = 6 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.UNIT_OF_MEASURE
    UNION ALL
    SELECT 2, 'A3_VOLUME', 'DIVISION', TO_NVARCHAR(COUNT(*)), '5',
           CASE WHEN COUNT(*) = 5 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.DIVISION
    UNION ALL
    SELECT 2, 'A3_VOLUME', 'CURRENCY', TO_NVARCHAR(COUNT(*)), '3',
           CASE WHEN COUNT(*) = 3 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.CURRENCY
    UNION ALL
    SELECT 2, 'A3_VOLUME', 'MATERIAL_DESCRIPTION', TO_NVARCHAR(COUNT(*)), '600',
           CASE WHEN COUNT(*) = 600 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.MATERIAL_DESCRIPTION
    UNION ALL
    SELECT 2, 'A3_VOLUME', 'MATERIAL_VALUATION', TO_NVARCHAR(COUNT(*)), '1080',
           CASE WHEN COUNT(*) = 1080 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.MATERIAL_VALUATION
    UNION ALL
    SELECT 2, 'A3_VOLUME', 'MATERIAL_UOM', TO_NVARCHAR(COUNT(*)), '574',
           CASE WHEN COUNT(*) = 574 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.MATERIAL_UOM
    UNION ALL
    SELECT 3, 'RULE', 'Procurement type vs material type', TO_NVARCHAR(COUNT(*)), '0',
           CASE WHEN COUNT(*) = 0 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.MATERIAL_PLANT MP
    INNER JOIN INDUSTRIAL_DATA.MATERIAL M ON M.MATNR = MP.MATNR
    WHERE NOT ( (M.MTART IN ('ROH','VERP') AND MP.PROCUREMENT_TYPE = 'F')
             OR (M.MTART = 'FERT' AND MP.PROCUREMENT_TYPE = 'E')
             OR (M.MTART = 'HALB' AND MP.PROCUREMENT_TYPE IN ('E','X')) )
    UNION ALL
    SELECT 3, 'RULE', 'Purchasing group field relevance', TO_NVARCHAR(COUNT(*)), '0',
           CASE WHEN COUNT(*) = 0 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.MATERIAL_PLANT
    WHERE (PROCUREMENT_TYPE = 'F' AND EKGRP IS NULL)
       OR (PROCUREMENT_TYPE <> 'F' AND EKGRP IS NOT NULL)
    UNION ALL
    SELECT 3, 'RULE', 'Reorder point field relevance', TO_NVARCHAR(COUNT(*)), '0',
           CASE WHEN COUNT(*) = 0 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.MATERIAL_PLANT
    WHERE (MRP_TYPE = 'VB' AND MINBE IS NULL) OR (MRP_TYPE <> 'VB' AND MINBE IS NOT NULL)
    UNION ALL
    SELECT 3, 'RULE', 'Valuation currency vs company code', TO_NVARCHAR(COUNT(*)), '0',
           CASE WHEN COUNT(*) = 0 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.MATERIAL_VALUATION MV
    INNER JOIN INDUSTRIAL_DATA.PLANT P ON P.WERKS = MV.BWKEY
    INNER JOIN INDUSTRIAL_DATA.COMPANY_CODE CC ON CC.BUKRS = P.BUKRS
    WHERE MV.WAERS <> CC.CURRENCY
    UNION ALL
    SELECT 3, 'RULE', 'Price control vs procurement type', TO_NVARCHAR(COUNT(*)), '0',
           CASE WHEN COUNT(*) = 0 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.MATERIAL_VALUATION MV
    INNER JOIN INDUSTRIAL_DATA.MATERIAL_PLANT MP ON MP.MATNR = MV.MATNR AND MP.WERKS = MV.BWKEY
    WHERE NOT ( (MV.VPRSV = 'V' AND MP.PROCUREMENT_TYPE = 'F')
             OR (MV.VPRSV = 'S' AND MP.PROCUREMENT_TYPE <> 'F') )
    UNION ALL
    SELECT 3, 'RULE', 'Material number range compliance', TO_NVARCHAR(COUNT(*)), '0',
           CASE WHEN COUNT(*) = 0 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.MATERIAL M
    INNER JOIN INDUSTRIAL_DATA.MATERIAL_TYPE T ON T.MTART = M.MTART
    WHERE TO_BIGINT(SUBSTRING(M.MATNR, LOCATE(M.MATNR, '-') + 1))
          NOT BETWEEN TO_BIGINT(T.INT_NUMBER_RANGE_FROM) AND TO_BIGINT(T.INT_NUMBER_RANGE_TO)
    UNION ALL
    SELECT 3, 'RULE', 'Materials without English description', TO_NVARCHAR(COUNT(*)), '0',
           CASE WHEN COUNT(*) = 0 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.MATERIAL M
    WHERE NOT EXISTS (SELECT 1 FROM INDUSTRIAL_DATA.MATERIAL_DESCRIPTION D
                      WHERE D.MATNR = M.MATNR AND D.SPRAS = 'EN')
    UNION ALL
    SELECT 3, 'RULE', 'Materials without base unit row', TO_NVARCHAR(COUNT(*)), '0',
           CASE WHEN COUNT(*) = 0 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.MATERIAL M
    WHERE NOT EXISTS (SELECT 1 FROM INDUSTRIAL_DATA.MATERIAL_UOM U
                      WHERE U.MATNR = M.MATNR AND U.MEINH = M.MEINS AND U.UMREZ = 1 AND U.UMREN = 1)
    UNION ALL
    SELECT 4, 'MULTICURRENCY_READINESS', 'Plant ' || MV.BWKEY || ' valuation currency',
           MAX(MV.WAERS) || ' - ' || TO_NVARCHAR(COUNT(*)) || ' valuated materials',
           'READY_FOR_FUTURE_CURRENCY_SCENARIO', 'INFO'
    FROM INDUSTRIAL_DATA.MATERIAL_VALUATION MV
    WHERE MV.BWKEY IN ('1200','2800')
    GROUP BY MV.BWKEY
)
ORDER BY SORT_ORDER, OBJECT_NAME;
