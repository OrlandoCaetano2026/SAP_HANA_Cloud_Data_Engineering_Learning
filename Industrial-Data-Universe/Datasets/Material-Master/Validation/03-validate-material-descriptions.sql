-- ============================================================================
-- A3 / DOC 03 - Validation 03/08: MATERIAL_DESCRIPTION (SAP MAKT)
-- Confirms 600 rows (300 EN + 300 PT), every material covered in both
-- languages, and shows a bilingual sample.
-- ============================================================================
SELECT * FROM (
    SELECT 1 AS SORT_ORDER, 'ROW_COUNT' AS CHECK_ITEM, 'MATERIAL_DESCRIPTION total' AS OBJECT_NAME,
           TO_NVARCHAR(COUNT(*)) AS ACTUAL_VALUE, '600' AS EXPECTED_VALUE,
           CASE WHEN COUNT(*) = 600 THEN 'PASSED' ELSE 'FAILED' END AS VALIDATION_STATUS
    FROM INDUSTRIAL_DATA.MATERIAL_DESCRIPTION
    UNION ALL
    SELECT 2, 'ROW_COUNT_BY_LANGUAGE', 'SPRAS ' || SPRAS, TO_NVARCHAR(COUNT(*)), '300',
           CASE WHEN COUNT(*) = 300 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.MATERIAL_DESCRIPTION GROUP BY SPRAS
    UNION ALL
    SELECT 3, 'COVERAGE', 'Materials without EN description',
           TO_NVARCHAR(COUNT(*)), '0',
           CASE WHEN COUNT(*) = 0 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.MATERIAL M
    WHERE NOT EXISTS (SELECT 1 FROM INDUSTRIAL_DATA.MATERIAL_DESCRIPTION D
                      WHERE D.MATNR = M.MATNR AND D.SPRAS = 'EN')
    UNION ALL
    SELECT 4, 'COVERAGE', 'Materials without PT description',
           TO_NVARCHAR(COUNT(*)), '0',
           CASE WHEN COUNT(*) = 0 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.MATERIAL M
    WHERE NOT EXISTS (SELECT 1 FROM INDUSTRIAL_DATA.MATERIAL_DESCRIPTION D
                      WHERE D.MATNR = M.MATNR AND D.SPRAS = 'PT')
    UNION ALL
    SELECT 5, 'SAMPLE_BILINGUAL', D.MATNR,
           MAX(CASE WHEN D.SPRAS = 'EN' THEN D.MAKTX END),
           MAX(CASE WHEN D.SPRAS = 'PT' THEN D.MAKTX END), 'INFO'
    FROM INDUSTRIAL_DATA.MATERIAL_DESCRIPTION D
    WHERE D.MATNR IN ('RM-100001','SA-400001','FG-500001','PK-600001','EC-200001')
    GROUP BY D.MATNR
)
ORDER BY SORT_ORDER, OBJECT_NAME;
