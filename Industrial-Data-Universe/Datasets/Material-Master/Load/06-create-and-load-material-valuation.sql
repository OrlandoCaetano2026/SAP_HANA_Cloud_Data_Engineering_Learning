-- Script 06/07 (Load): currency check table + MATERIAL_VALUATION (SAP MBEW)
-- Target schema : INDUSTRIAL_DATA
-- Valuation area: PLANT (S/4 default) -> BWKEY = WERKS
-- Currency      : derived from PLANT.BUKRS -> COMPANY_CODE.CURRENCY, never
--                 hard-coded, so a future USD scenario needs data only.
-- Price control : S (standard) for in-house produced, V (moving average) for
--                 externally procured - inherited from MATERIAL_TYPE.
-- Price formula : mixes the material number with a large prime (104729) and a
--                 second prime (7919) on the plant, so consecutive material
--                 numbers spread across the whole interval of their type.
-- ============================================================================

-- 1) CURRENCY check table (SAP TCURC) ---------------------------------------
CREATE COLUMN TABLE INDUSTRIAL_DATA.CURRENCY (
    WAERS          NVARCHAR(3)  NOT NULL,
    CURRENCY_NAME  NVARCHAR(40) NOT NULL,
    DECIMAL_PLACES INTEGER      NOT NULL,
    ISO_CODE       NVARCHAR(3)  NOT NULL,
    PRIMARY KEY (WAERS)
);

INSERT INTO INDUSTRIAL_DATA.CURRENCY VALUES ('BRL','Brazilian Real',2,'BRL');
INSERT INTO INDUSTRIAL_DATA.CURRENCY VALUES ('USD','US Dollar',2,'USD');
INSERT INTO INDUSTRIAL_DATA.CURRENCY VALUES ('EUR','Euro',2,'EUR');

-- 2) Retro-fit domain integrity onto the A2 enterprise structure ------------
ALTER TABLE INDUSTRIAL_DATA.COMPANY_CODE ADD CONSTRAINT FK_COMPANY_CODE_CURRENCY
    FOREIGN KEY (CURRENCY) REFERENCES INDUSTRIAL_DATA.CURRENCY (WAERS);

-- 3) MATERIAL_VALUATION (SAP MBEW) ----------------------------------------
CREATE COLUMN TABLE INDUSTRIAL_DATA.MATERIAL_VALUATION (
    MATNR NVARCHAR(40)  NOT NULL,
    BWKEY NVARCHAR(4)   NOT NULL,
    BWTAR NVARCHAR(10)  NOT NULL,
    BKLAS NVARCHAR(4)   NOT NULL,
    VPRSV NVARCHAR(1)   NOT NULL,
    STPRS DECIMAL(13,2),
    VERPR DECIMAL(13,2),
    PEINH INTEGER       NOT NULL,
    WAERS NVARCHAR(3)   NOT NULL,
    PRIMARY KEY (MATNR, BWKEY, BWTAR),
    CONSTRAINT FK_MATERIAL_VALUATION_MATERIAL_PLANT
        FOREIGN KEY (MATNR, BWKEY) REFERENCES INDUSTRIAL_DATA.MATERIAL_PLANT (MATNR, WERKS),
    CONSTRAINT FK_MATERIAL_VALUATION_CURRENCY
        FOREIGN KEY (WAERS) REFERENCES INDUSTRIAL_DATA.CURRENCY (WAERS),
    CONSTRAINT CHK_MATERIAL_VALUATION_VPRSV CHECK (VPRSV IN ('S','V')),
    CONSTRAINT CHK_MATERIAL_VALUATION_PEINH CHECK (PEINH IN (1,10,100,1000)),
    CONSTRAINT CHK_MATERIAL_VALUATION_PRICE CHECK (
        (VPRSV = 'S' AND STPRS IS NOT NULL AND VERPR IS NULL) OR
        (VPRSV = 'V' AND VERPR IS NOT NULL AND STPRS IS NULL)
    )
);

-- 4) Load: one valuation record per material-plant, currency derived --------
INSERT INTO INDUSTRIAL_DATA.MATERIAL_VALUATION
    (MATNR, BWKEY, BWTAR, BKLAS, VPRSV, STPRS, VERPR, PEINH, WAERS)
SELECT V.MATNR, V.BWKEY, 'STD', V.BKLAS, V.VPRSV,
       CASE WHEN V.VPRSV = 'S' THEN V.PRICE END,
       CASE WHEN V.VPRSV = 'V' THEN V.PRICE END,
       V.PEINH, V.WAERS
FROM (
    SELECT
        MP.MATNR AS MATNR,
        MP.WERKS AS BWKEY,
        T.DEFAULT_VALUATION_CLASS AS BKLAS,
        T.DEFAULT_PRICE_CONTROL   AS VPRSV,
        CASE WHEN M.MTART = 'VERP' THEN 100 ELSE 1 END AS PEINH,
        CC.CURRENCY AS WAERS,
        CASE M.MTART
            WHEN 'VERP' THEN ROUND(0.50    + MOD(TO_BIGINT(SUBSTRING(MP.MATNR, LOCATE(MP.MATNR,'-') + 1)) * 104729 + TO_BIGINT(MP.WERKS) * 7919, 1950)    / 100.0, 2)
            WHEN 'ROH'  THEN ROUND(5.00    + MOD(TO_BIGINT(SUBSTRING(MP.MATNR, LOCATE(MP.MATNR,'-') + 1)) * 104729 + TO_BIGINT(MP.WERKS) * 7919, 19500)   / 100.0, 2)
            WHEN 'HALB' THEN ROUND(200.00  + MOD(TO_BIGINT(SUBSTRING(MP.MATNR, LOCATE(MP.MATNR,'-') + 1)) * 104729 + TO_BIGINT(MP.WERKS) * 7919, 180000)  / 100.0, 2)
            WHEN 'FERT' THEN ROUND(2000.00 + MOD(TO_BIGINT(SUBSTRING(MP.MATNR, LOCATE(MP.MATNR,'-') + 1)) * 104729 + TO_BIGINT(MP.WERKS) * 7919, 1800000) / 100.0, 2)
        END AS PRICE
    FROM INDUSTRIAL_DATA.MATERIAL_PLANT MP
    INNER JOIN INDUSTRIAL_DATA.MATERIAL      M  ON M.MATNR  = MP.MATNR
    INNER JOIN INDUSTRIAL_DATA.MATERIAL_TYPE T  ON T.MTART  = M.MTART
    INNER JOIN INDUSTRIAL_DATA.PLANT         P  ON P.WERKS  = MP.WERKS
    INNER JOIN INDUSTRIAL_DATA.COMPANY_CODE  CC ON CC.BUKRS = P.BUKRS
    WHERE T.IS_VALUE_UPDATED = 'Y'
) V;

COMMIT;
