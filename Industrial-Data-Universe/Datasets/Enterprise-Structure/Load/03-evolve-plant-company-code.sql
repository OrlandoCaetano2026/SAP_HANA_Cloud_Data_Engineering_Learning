-- Evolves the existing PLANT table and connects every Plant to a Company Code.

ALTER TABLE INDUSTRIAL_DATA.PLANT
ADD (
    BUKRS NVARCHAR(4)
);

UPDATE INDUSTRIAL_DATA.PLANT
SET BUKRS = 'FBR1'
WHERE WERKS IN ('1000', '1100', '1400', '1500', '1600', '1700', '1800', '1900', '2900');

UPDATE INDUSTRIAL_DATA.PLANT
SET BUKRS = 'FBR2'
WHERE WERKS IN ('1200', '1300');

UPDATE INDUSTRIAL_DATA.PLANT
SET BUKRS = 'FBR3'
WHERE WERKS IN ('2000', '2100', '2200', '2300', '2700', '2800');

UPDATE INDUSTRIAL_DATA.PLANT
SET BUKRS = 'FBR4'
WHERE WERKS IN ('2400', '2500', '2600');

COMMIT;

ALTER TABLE INDUSTRIAL_DATA.PLANT
ALTER (
    BUKRS NVARCHAR(4) NOT NULL
);

ALTER TABLE INDUSTRIAL_DATA.PLANT
ADD CONSTRAINT FK_PLANT_COMPANY_CODE
FOREIGN KEY (BUKRS)
REFERENCES INDUSTRIAL_DATA.COMPANY_CODE (BUKRS);
