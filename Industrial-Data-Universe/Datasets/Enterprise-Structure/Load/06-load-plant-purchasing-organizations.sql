-- Creates 20 PRIMARY and 13 STRATEGIC_SUPPORT assignments.

INSERT INTO INDUSTRIAL_DATA.PLANT_PURCHASING_ORG (
    WERKS,
    EKORG,
    ASSIGNMENT_TYPE
)
SELECT
    WERKS,
    CASE BUKRS
        WHEN 'FBR1' THEN 'P110'
        WHEN 'FBR2' THEN 'P120'
        WHEN 'FBR3' THEN 'P130'
        WHEN 'FBR4' THEN 'P140'
    END,
    'PRIMARY'
FROM INDUSTRIAL_DATA.PLANT
WHERE BUKRS IN ('FBR1', 'FBR2', 'FBR3', 'FBR4');

INSERT INTO INDUSTRIAL_DATA.PLANT_PURCHASING_ORG (
    WERKS,
    EKORG,
    ASSIGNMENT_TYPE
)
SELECT
    WERKS,
    'P100',
    'STRATEGIC_SUPPORT'
FROM INDUSTRIAL_DATA.PLANT
WHERE WERKS IN (
    '1000', '1200', '1300', '1400', '1500', '1600', '1700',
    '1800', '1900', '2300', '2400', '2800', '2900'
);

COMMIT;

SELECT
    COUNT(1) AS TOTAL_ASSIGNMENTS,
    COUNT(DISTINCT WERKS) AS PLANTS_WITH_ASSIGNMENTS,
    COUNT(DISTINCT EKORG) AS PURCHASING_ORGANIZATIONS_USED,
    SUM(CASE WHEN ASSIGNMENT_TYPE = 'PRIMARY' THEN 1 ELSE 0 END) AS PRIMARY_ASSIGNMENTS,
    SUM(CASE WHEN ASSIGNMENT_TYPE = 'STRATEGIC_SUPPORT' THEN 1 ELSE 0 END) AS STRATEGIC_ASSIGNMENTS
FROM INDUSTRIAL_DATA.PLANT_PURCHASING_ORG;
