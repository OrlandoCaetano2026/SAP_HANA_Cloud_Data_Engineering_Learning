-- Creates the SAP-inspired enterprise and purchasing structures.
-- Target schema: INDUSTRIAL_DATA

CREATE COLUMN TABLE INDUSTRIAL_DATA.COMPANY (
    COMPANY_ID NVARCHAR(4) NOT NULL,
    COMPANY_NAME NVARCHAR(100) NOT NULL,
    COUNTRY NVARCHAR(3) NOT NULL,
    PRIMARY KEY (COMPANY_ID)
);

CREATE COLUMN TABLE INDUSTRIAL_DATA.COMPANY_CODE (
    BUKRS NVARCHAR(4) NOT NULL,
    COMPANY_ID NVARCHAR(4) NOT NULL,
    COMPANY_CODE_NAME NVARCHAR(100) NOT NULL,
    COUNTRY NVARCHAR(3) NOT NULL,
    CURRENCY NVARCHAR(3) NOT NULL,
    PROFILE NVARCHAR(30) NOT NULL,
    PRIMARY KEY (BUKRS),
    CONSTRAINT FK_COMPANY_CODE_COMPANY
        FOREIGN KEY (COMPANY_ID)
        REFERENCES INDUSTRIAL_DATA.COMPANY (COMPANY_ID)
);

CREATE COLUMN TABLE INDUSTRIAL_DATA.PURCHASING_ORGANIZATION (
    EKORG NVARCHAR(4) NOT NULL,
    PURCHASING_ORG_NAME NVARCHAR(100) NOT NULL,
    ORGANIZATION_SCOPE NVARCHAR(30) NOT NULL,
    PRIMARY_BUKRS NVARCHAR(4),
    PRIMARY KEY (EKORG),
    CONSTRAINT FK_PURCHASING_ORG_COMPANY_CODE
        FOREIGN KEY (PRIMARY_BUKRS)
        REFERENCES INDUSTRIAL_DATA.COMPANY_CODE (BUKRS)
);

CREATE COLUMN TABLE INDUSTRIAL_DATA.PURCHASING_GROUP (
    EKGRP NVARCHAR(3) NOT NULL,
    PURCHASING_GROUP_NAME NVARCHAR(100) NOT NULL,
    RESPONSIBILITY_AREA NVARCHAR(40) NOT NULL,
    PRIMARY KEY (EKGRP)
);

CREATE COLUMN TABLE INDUSTRIAL_DATA.PLANT_PURCHASING_ORG (
    WERKS NVARCHAR(4) NOT NULL,
    EKORG NVARCHAR(4) NOT NULL,
    ASSIGNMENT_TYPE NVARCHAR(20) NOT NULL,
    PRIMARY KEY (WERKS, EKORG),
    CONSTRAINT FK_PLANT_PURCH_ORG_PLANT
        FOREIGN KEY (WERKS)
        REFERENCES INDUSTRIAL_DATA.PLANT (WERKS),
    CONSTRAINT FK_PLANT_PURCH_ORG_PURCH_ORG
        FOREIGN KEY (EKORG)
        REFERENCES INDUSTRIAL_DATA.PURCHASING_ORGANIZATION (EKORG)
);
