-- Final A2 reconciliation: 10 tables, 10 logical FKs and 3,770 total records.

SELECT
    VALIDATION_RULE,
    ACTUAL_VALUE,
    EXPECTED_VALUE,
    CASE WHEN ACTUAL_VALUE = EXPECTED_VALUE THEN 'PASSED' ELSE 'FAILED' END AS VALIDATION_STATUS
FROM (
    SELECT 'A2_NEW_RECORD_COUNT' AS VALIDATION_RULE,
        (SELECT COUNT(1) FROM INDUSTRIAL_DATA.COMPANY)
        + (SELECT COUNT(1) FROM INDUSTRIAL_DATA.COMPANY_CODE)
        + (SELECT COUNT(1) FROM INDUSTRIAL_DATA.PURCHASING_ORGANIZATION)
        + (SELECT COUNT(1) FROM INDUSTRIAL_DATA.PURCHASING_GROUP)
        + (SELECT COUNT(1) FROM INDUSTRIAL_DATA.PLANT_PURCHASING_ORG) AS ACTUAL_VALUE,
        55 AS EXPECTED_VALUE
    FROM DUMMY
    UNION ALL
    SELECT 'ASSIGNMENTS_WITHOUT_PLANT', COUNT(1), 0
    FROM INDUSTRIAL_DATA.PLANT_PURCHASING_ORG PPO
    LEFT JOIN INDUSTRIAL_DATA.PLANT P ON P.WERKS = PPO.WERKS
    WHERE P.WERKS IS NULL
    UNION ALL
    SELECT 'ASSIGNMENTS_WITHOUT_PURCHASING_ORG', COUNT(1), 0
    FROM INDUSTRIAL_DATA.PLANT_PURCHASING_ORG PPO
    LEFT JOIN INDUSTRIAL_DATA.PURCHASING_ORGANIZATION PO ON PO.EKORG = PPO.EKORG
    WHERE PO.EKORG IS NULL
    UNION ALL
    SELECT 'COMPANY_CODES_WITHOUT_COMPANY', COUNT(1), 0
    FROM INDUSTRIAL_DATA.COMPANY_CODE CC
    LEFT JOIN INDUSTRIAL_DATA.COMPANY C ON C.COMPANY_ID = CC.COMPANY_ID
    WHERE C.COMPANY_ID IS NULL
    UNION ALL
    SELECT 'COMPANY_CODE_COUNT', COUNT(1), 4 FROM INDUSTRIAL_DATA.COMPANY_CODE
    UNION ALL
    SELECT 'COMPANY_COUNT', COUNT(1), 1 FROM INDUSTRIAL_DATA.COMPANY
    UNION ALL
    SELECT 'DUPLICATE_PLANT_PURCHASING_ORG_PK', COUNT(1), 0
    FROM (
        SELECT WERKS, EKORG
        FROM INDUSTRIAL_DATA.PLANT_PURCHASING_ORG
        GROUP BY WERKS, EKORG
        HAVING COUNT(1) > 1
    ) AS DUPLICATE_ASSIGNMENTS
    UNION ALL
    SELECT 'ENFORCED_FOREIGN_KEY_COUNT', COUNT(DISTINCT CONSTRAINT_NAME), 10
    FROM SYS.REFERENTIAL_CONSTRAINTS
    WHERE SCHEMA_NAME = 'INDUSTRIAL_DATA' AND IS_ENFORCED = 'TRUE'
    UNION ALL
    SELECT 'FOREIGN_KEY_COUNT', COUNT(DISTINCT CONSTRAINT_NAME), 10
    FROM SYS.REFERENTIAL_CONSTRAINTS WHERE SCHEMA_NAME = 'INDUSTRIAL_DATA'
    UNION ALL
    SELECT 'FOUNDATION_RECORD_COUNT',
        (SELECT COUNT(1) FROM INDUSTRIAL_DATA.PLANT)
        + (SELECT COUNT(1) FROM INDUSTRIAL_DATA.MATERIAL)
        + (SELECT COUNT(1) FROM INDUSTRIAL_DATA.STORAGE_LOCATION)
        + (SELECT COUNT(1) FROM INDUSTRIAL_DATA.MATERIAL_PLANT)
        + (SELECT COUNT(1) FROM INDUSTRIAL_DATA.MATERIAL_STORAGE_LOCATION),
        3715
    FROM DUMMY
    UNION ALL
    SELECT 'INDUSTRIAL_DATA_TABLE_COUNT', COUNT(1), 10
    FROM SYS.TABLES WHERE SCHEMA_NAME = 'INDUSTRIAL_DATA'
    UNION ALL
    SELECT 'PLANT_COUNT', COUNT(1), 20 FROM INDUSTRIAL_DATA.PLANT
    UNION ALL
    SELECT 'PLANT_PURCHASING_ORG_COUNT', COUNT(1), 33 FROM INDUSTRIAL_DATA.PLANT_PURCHASING_ORG
    UNION ALL
    SELECT 'PLANTS_WITH_NULL_BUKRS', COUNT(1), 0
    FROM INDUSTRIAL_DATA.PLANT WHERE BUKRS IS NULL
    UNION ALL
    SELECT 'PLANTS_WITH_UNKNOWN_BUKRS', COUNT(1), 0
    FROM INDUSTRIAL_DATA.PLANT P
    LEFT JOIN INDUSTRIAL_DATA.COMPANY_CODE CC ON CC.BUKRS = P.BUKRS
    WHERE CC.BUKRS IS NULL
    UNION ALL
    SELECT 'PLANTS_WITHOUT_PRIMARY_PURCHASING_ORG', COUNT(1), 0
    FROM INDUSTRIAL_DATA.PLANT P
    LEFT JOIN INDUSTRIAL_DATA.PLANT_PURCHASING_ORG PPO
        ON PPO.WERKS = P.WERKS AND PPO.ASSIGNMENT_TYPE = 'PRIMARY'
    WHERE PPO.WERKS IS NULL
    UNION ALL
    SELECT 'PURCHASING_GROUP_COUNT', COUNT(1), 12 FROM INDUSTRIAL_DATA.PURCHASING_GROUP
    UNION ALL
    SELECT 'PURCHASING_ORGANIZATION_COUNT', COUNT(1), 5 FROM INDUSTRIAL_DATA.PURCHASING_ORGANIZATION
    UNION ALL
    SELECT 'TOTAL_INDUSTRIAL_DATA_RECORD_COUNT',
        (SELECT COUNT(1) FROM INDUSTRIAL_DATA.COMPANY)
        + (SELECT COUNT(1) FROM INDUSTRIAL_DATA.COMPANY_CODE)
        + (SELECT COUNT(1) FROM INDUSTRIAL_DATA.PLANT)
        + (SELECT COUNT(1) FROM INDUSTRIAL_DATA.STORAGE_LOCATION)
        + (SELECT COUNT(1) FROM INDUSTRIAL_DATA.MATERIAL)
        + (SELECT COUNT(1) FROM INDUSTRIAL_DATA.MATERIAL_PLANT)
        + (SELECT COUNT(1) FROM INDUSTRIAL_DATA.MATERIAL_STORAGE_LOCATION)
        + (SELECT COUNT(1) FROM INDUSTRIAL_DATA.PURCHASING_ORGANIZATION)
        + (SELECT COUNT(1) FROM INDUSTRIAL_DATA.PURCHASING_GROUP)
        + (SELECT COUNT(1) FROM INDUSTRIAL_DATA.PLANT_PURCHASING_ORG),
        3770
    FROM DUMMY
    UNION ALL
    SELECT 'VALIDATED_FOREIGN_KEY_COUNT', COUNT(DISTINCT CONSTRAINT_NAME), 10
    FROM SYS.REFERENTIAL_CONSTRAINTS
    WHERE SCHEMA_NAME = 'INDUSTRIAL_DATA' AND IS_VALIDATED = 'TRUE'
) AS A2_FINAL_RECONCILIATION
ORDER BY VALIDATION_RULE;
