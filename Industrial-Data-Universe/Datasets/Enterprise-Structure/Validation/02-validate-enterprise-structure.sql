-- Validates Company, Company Code and evolved Plant relationships.

SELECT
    C.COMPANY_ID,
    C.COMPANY_NAME,
    CC.BUKRS,
    CC.COMPANY_CODE_NAME,
    CC.COUNTRY,
    CC.CURRENCY,
    CC.PROFILE,
    COUNT(P.WERKS) AS PLANT_COUNT,
    CASE
        WHEN CC.BUKRS = 'FBR1' AND COUNT(P.WERKS) = 9 THEN 'PASSED'
        WHEN CC.BUKRS = 'FBR2' AND COUNT(P.WERKS) = 2 THEN 'PASSED'
        WHEN CC.BUKRS = 'FBR3' AND COUNT(P.WERKS) = 6 THEN 'PASSED'
        WHEN CC.BUKRS = 'FBR4' AND COUNT(P.WERKS) = 3 THEN 'PASSED'
        ELSE 'FAILED'
    END AS VALIDATION_STATUS
FROM INDUSTRIAL_DATA.COMPANY C
INNER JOIN INDUSTRIAL_DATA.COMPANY_CODE CC
    ON CC.COMPANY_ID = C.COMPANY_ID
LEFT JOIN INDUSTRIAL_DATA.PLANT P
    ON P.BUKRS = CC.BUKRS
GROUP BY
    C.COMPANY_ID,
    C.COMPANY_NAME,
    CC.BUKRS,
    CC.COMPANY_CODE_NAME,
    CC.COUNTRY,
    CC.CURRENCY,
    CC.PROFILE
ORDER BY CC.BUKRS;
