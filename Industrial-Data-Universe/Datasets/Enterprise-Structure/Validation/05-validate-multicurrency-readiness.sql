-- Validates organizational readiness only. Currency conversion is not implemented in A2.

SELECT
    P.WERKS,
    P.PLANT_NAME,
    P.BUKRS,
    CC.COMPANY_CODE_NAME,
    CC.CURRENCY AS LOCAL_CURRENCY,
    'USD' AS FUTURE_DOCUMENT_CURRENCY,
    MAX(CASE WHEN PPO.ASSIGNMENT_TYPE = 'PRIMARY' THEN PPO.EKORG END) AS PRIMARY_EKORG,
    MAX(CASE WHEN PPO.ASSIGNMENT_TYPE = 'PRIMARY' THEN PO.PURCHASING_ORG_NAME END) AS PRIMARY_PURCHASING_ORG,
    MAX(CASE WHEN PPO.ASSIGNMENT_TYPE = 'STRATEGIC_SUPPORT' THEN PPO.EKORG END) AS STRATEGIC_EKORG,
    MAX(CASE WHEN PPO.ASSIGNMENT_TYPE = 'STRATEGIC_SUPPORT' THEN PO.PURCHASING_ORG_NAME END) AS STRATEGIC_PURCHASING_ORG,
    COUNT(DISTINCT PPO.EKORG) AS PURCHASING_ORG_COUNT,
    CASE
        WHEN CC.CURRENCY = 'BRL'
         AND COUNT(DISTINCT PPO.EKORG) = 2
         AND MAX(CASE WHEN PPO.ASSIGNMENT_TYPE = 'PRIMARY' THEN PPO.EKORG END) IS NOT NULL
         AND MAX(CASE WHEN PPO.ASSIGNMENT_TYPE = 'STRATEGIC_SUPPORT' THEN PPO.EKORG END) = 'P100'
            THEN 'READY_FOR_FUTURE_CURRENCY_SCENARIO'
        ELSE 'NOT_READY'
    END AS READINESS_STATUS
FROM INDUSTRIAL_DATA.PLANT P
INNER JOIN INDUSTRIAL_DATA.COMPANY_CODE CC ON CC.BUKRS = P.BUKRS
INNER JOIN INDUSTRIAL_DATA.PLANT_PURCHASING_ORG PPO ON PPO.WERKS = P.WERKS
INNER JOIN INDUSTRIAL_DATA.PURCHASING_ORGANIZATION PO ON PO.EKORG = PPO.EKORG
WHERE P.WERKS IN ('1200', '2800')
GROUP BY P.WERKS, P.PLANT_NAME, P.BUKRS, CC.COMPANY_CODE_NAME, CC.CURRENCY
ORDER BY P.WERKS;
