-- Provides an end-to-end organizational and purchasing view.

SELECT
    C.COMPANY_ID,
    C.COMPANY_NAME,
    CC.BUKRS,
    CC.COMPANY_CODE_NAME,
    CC.CURRENCY AS LOCAL_CURRENCY,
    P.WERKS,
    P.PLANT_NAME,
    PPO.EKORG,
    PO.PURCHASING_ORG_NAME,
    PO.ORGANIZATION_SCOPE,
    PPO.ASSIGNMENT_TYPE,
    CASE
        WHEN PPO.ASSIGNMENT_TYPE = 'PRIMARY'
         AND PO.PRIMARY_BUKRS = P.BUKRS
            THEN 'PASSED'
        WHEN PPO.ASSIGNMENT_TYPE = 'STRATEGIC_SUPPORT'
         AND PO.ORGANIZATION_SCOPE = 'CROSS_COMPANY_CODE'
         AND PO.PRIMARY_BUKRS IS NULL
            THEN 'PASSED'
        ELSE 'FAILED'
    END AS RELATIONSHIP_STATUS
FROM INDUSTRIAL_DATA.COMPANY C
INNER JOIN INDUSTRIAL_DATA.COMPANY_CODE CC ON CC.COMPANY_ID = C.COMPANY_ID
INNER JOIN INDUSTRIAL_DATA.PLANT P ON P.BUKRS = CC.BUKRS
INNER JOIN INDUSTRIAL_DATA.PLANT_PURCHASING_ORG PPO ON PPO.WERKS = P.WERKS
INNER JOIN INDUSTRIAL_DATA.PURCHASING_ORGANIZATION PO ON PO.EKORG = PPO.EKORG
ORDER BY CC.BUKRS, P.WERKS, PPO.ASSIGNMENT_TYPE, PPO.EKORG;
