-- Reconciles the physical schema after LAB_A1 was renamed to INDUSTRIAL_DATA.

SELECT
    VALIDATION_RULE,
    ACTUAL_VALUE,
    EXPECTED_VALUE,
    CASE WHEN ACTUAL_VALUE = EXPECTED_VALUE THEN 'PASSED' ELSE 'FAILED' END AS VALIDATION_STATUS
FROM (
    SELECT 'SOURCE_SCHEMA_DOES_NOT_EXIST' AS VALIDATION_RULE, COUNT(1) AS ACTUAL_VALUE, 0 AS EXPECTED_VALUE
    FROM SYS.SCHEMAS WHERE SCHEMA_NAME = 'LAB_A1'
    UNION ALL
    SELECT 'TARGET_SCHEMA_EXISTS', COUNT(1), 1
    FROM SYS.SCHEMAS WHERE SCHEMA_NAME = 'INDUSTRIAL_DATA'
    UNION ALL
    SELECT 'TARGET_TABLE_COUNT', COUNT(1), 5
    FROM SYS.TABLES WHERE SCHEMA_NAME = 'INDUSTRIAL_DATA'
      AND TABLE_NAME IN ('PLANT', 'MATERIAL', 'STORAGE_LOCATION', 'MATERIAL_PLANT', 'MATERIAL_STORAGE_LOCATION')
    UNION ALL
    SELECT 'FOUNDATION_FOREIGN_KEY_COUNT', COUNT(DISTINCT CONSTRAINT_NAME), 5
    FROM SYS.REFERENTIAL_CONSTRAINTS WHERE SCHEMA_NAME = 'INDUSTRIAL_DATA'
    UNION ALL
    SELECT 'FOUNDATION_RECORD_COUNT',
        (SELECT COUNT(1) FROM INDUSTRIAL_DATA.PLANT)
        + (SELECT COUNT(1) FROM INDUSTRIAL_DATA.MATERIAL)
        + (SELECT COUNT(1) FROM INDUSTRIAL_DATA.STORAGE_LOCATION)
        + (SELECT COUNT(1) FROM INDUSTRIAL_DATA.MATERIAL_PLANT)
        + (SELECT COUNT(1) FROM INDUSTRIAL_DATA.MATERIAL_STORAGE_LOCATION),
        3715
    FROM DUMMY
) AS SCHEMA_MIGRATION_AUDIT
ORDER BY VALIDATION_RULE;
