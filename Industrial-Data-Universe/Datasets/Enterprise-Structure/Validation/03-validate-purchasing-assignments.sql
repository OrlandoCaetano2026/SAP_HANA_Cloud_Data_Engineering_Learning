-- Audits coverage, assignment types, referential integrity and key uniqueness.

SELECT
    VALIDATION_RULE,
    ACTUAL_VALUE,
    EXPECTED_VALUE,
    CASE WHEN ACTUAL_VALUE = EXPECTED_VALUE THEN 'PASSED' ELSE 'FAILED' END AS VALIDATION_STATUS
FROM (
    SELECT 'TOTAL_ASSIGNMENT_COUNT' AS VALIDATION_RULE, COUNT(1) AS ACTUAL_VALUE, 33 AS EXPECTED_VALUE
    FROM INDUSTRIAL_DATA.PLANT_PURCHASING_ORG
    UNION ALL
    SELECT 'PLANTS_WITH_ASSIGNMENT_COUNT', COUNT(DISTINCT WERKS), 20
    FROM INDUSTRIAL_DATA.PLANT_PURCHASING_ORG
    UNION ALL
    SELECT 'PURCHASING_ORGANIZATION_USAGE_COUNT', COUNT(DISTINCT EKORG), 5
    FROM INDUSTRIAL_DATA.PLANT_PURCHASING_ORG
    UNION ALL
    SELECT 'PRIMARY_ASSIGNMENT_COUNT', COUNT(1), 20
    FROM INDUSTRIAL_DATA.PLANT_PURCHASING_ORG WHERE ASSIGNMENT_TYPE = 'PRIMARY'
    UNION ALL
    SELECT 'STRATEGIC_SUPPORT_ASSIGNMENT_COUNT', COUNT(1), 13
    FROM INDUSTRIAL_DATA.PLANT_PURCHASING_ORG WHERE ASSIGNMENT_TYPE = 'STRATEGIC_SUPPORT'
    UNION ALL
    SELECT 'PLANTS_WITHOUT_PRIMARY_ASSIGNMENT', COUNT(1), 0
    FROM INDUSTRIAL_DATA.PLANT P
    LEFT JOIN INDUSTRIAL_DATA.PLANT_PURCHASING_ORG PPO
        ON PPO.WERKS = P.WERKS AND PPO.ASSIGNMENT_TYPE = 'PRIMARY'
    WHERE PPO.WERKS IS NULL
    UNION ALL
    SELECT 'PLANTS_WITH_MULTIPLE_PRIMARY_ASSIGNMENTS', COUNT(1), 0
    FROM (
        SELECT WERKS
        FROM INDUSTRIAL_DATA.PLANT_PURCHASING_ORG
        WHERE ASSIGNMENT_TYPE = 'PRIMARY'
        GROUP BY WERKS
        HAVING COUNT(1) <> 1
    ) AS MULTIPLE_PRIMARY
    UNION ALL
    SELECT 'ASSIGNMENTS_WITHOUT_PLANT', COUNT(1), 0
    FROM INDUSTRIAL_DATA.PLANT_PURCHASING_ORG PPO
    LEFT JOIN INDUSTRIAL_DATA.PLANT P ON P.WERKS = PPO.WERKS
    WHERE P.WERKS IS NULL
    UNION ALL
    SELECT 'ASSIGNMENTS_WITHOUT_PURCHASING_ORG', COUNT(1), 0
    FROM INDUSTRIAL_DATA.PLANT_PURCHASING_ORG PPO
    LEFT JOIN INDUSTRIAL_DATA.PURCHASING_ORGANIZATION PO ON PO.EKORG = PPO.EKORG
    WHERE PO.EKORG IS NULL
    UNION ALL
    SELECT 'DUPLICATE_PLANT_PURCHASING_ORG_PK', COUNT(1), 0
    FROM (
        SELECT WERKS, EKORG
        FROM INDUSTRIAL_DATA.PLANT_PURCHASING_ORG
        GROUP BY WERKS, EKORG
        HAVING COUNT(1) > 1
    ) AS DUPLICATE_PK
) AS PURCHASING_ASSIGNMENT_AUDIT
ORDER BY VALIDATION_RULE;
