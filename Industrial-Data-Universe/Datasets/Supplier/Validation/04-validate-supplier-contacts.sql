-- ============================================================================
-- A4 / DOC 04 - Supplier / Business Partner Foundation
-- Validation 04/08: SUPPLIER_CONTACT bilingual coverage
-- Confirms ~140 total contacts (~70 EN + ~70 PT), language distribution,
-- department coverage, and primary contact logic (one per language per supplier).
-- ============================================================================
SELECT * FROM (
    SELECT 1 AS SORT_ORDER, 'ROW_COUNT' AS CHECK_ITEM, 'SUPPLIER_CONTACT total' AS OBJECT_NAME,
           TO_NVARCHAR(COUNT(*)) AS ACTUAL_VALUE, '~140 (2 per supplier)' AS EXPECTED_VALUE,
           CASE WHEN COUNT(*) = 140 THEN 'PASSED' ELSE 'FAILED' END AS VALIDATION_STATUS
    FROM INDUSTRIAL_DATA.SUPPLIER_CONTACT
    UNION ALL
    SELECT 2, 'LANGUAGE_EN', 'English contacts (EN)',
           TO_NVARCHAR(COUNT(*)), '70',
           CASE WHEN COUNT(*) = 70 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.SUPPLIER_CONTACT
    WHERE CONTACT_LANGUAGE = 'EN'
    UNION ALL
    SELECT 3, 'LANGUAGE_PT', 'Portuguese contacts (PT)',
           TO_NVARCHAR(COUNT(*)), '70',
           CASE WHEN COUNT(*) = 70 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.SUPPLIER_CONTACT
    WHERE CONTACT_LANGUAGE = 'PT'
    UNION ALL
    SELECT 4, 'PRIMARY_CONTACT_EN', 'EN contacts with PRIMARY_CONTACT=Y',
           TO_NVARCHAR(COUNT(*)), '70',
           CASE WHEN COUNT(*) = 70 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.SUPPLIER_CONTACT
    WHERE CONTACT_LANGUAGE = 'EN' AND PRIMARY_CONTACT = 'Y'
    UNION ALL
    SELECT 5, 'PRIMARY_CONTACT_PT', 'PT contacts with PRIMARY_CONTACT=N',
           TO_NVARCHAR(COUNT(*)), '70',
           CASE WHEN COUNT(*) = 70 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.SUPPLIER_CONTACT
    WHERE CONTACT_LANGUAGE = 'PT' AND PRIMARY_CONTACT = 'N'
    UNION ALL
    SELECT 6, 'FK_SUPPLIER_CONTACT_SUPPLIER', 'Invalid SUPPLIER FKs',
           TO_NVARCHAR(COUNT(*)), '0',
           CASE WHEN COUNT(*) = 0 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.SUPPLIER_CONTACT SC
    WHERE NOT EXISTS (SELECT 1 FROM INDUSTRIAL_DATA.SUPPLIER S WHERE S.LIFNR = SC.LIFNR)
    UNION ALL
    SELECT 7, 'DEPARTMENT_COVERAGE', 'All dept types present (SALES/QUALITY/LOGISTICS/BILLING)',
           TO_NVARCHAR(COUNT(DISTINCT CONTACT_DEPARTMENT)), '4',
           CASE WHEN COUNT(DISTINCT CONTACT_DEPARTMENT) = 4 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.SUPPLIER_CONTACT
    UNION ALL
    SELECT 8, 'EMAIL_FORMAT', 'Email addresses with valid domain suffix',
           TO_NVARCHAR(SUM(CASE WHEN CONTACT_EMAIL LIKE '%.com' OR CONTACT_EMAIL LIKE '%.com.br' THEN 1 ELSE 0 END)),
           '~140',
           'INFO'
    FROM INDUSTRIAL_DATA.SUPPLIER_CONTACT
    UNION ALL
    SELECT 9, 'PHONE_FORMAT', 'Phone numbers with +55 11 prefix',
           TO_NVARCHAR(SUM(CASE WHEN CONTACT_PHONE LIKE '+55 11%' THEN 1 ELSE 0 END)),
           '~140',
           'INFO'
    FROM INDUSTRIAL_DATA.SUPPLIER_CONTACT
)
ORDER BY SORT_ORDER, OBJECT_NAME;
