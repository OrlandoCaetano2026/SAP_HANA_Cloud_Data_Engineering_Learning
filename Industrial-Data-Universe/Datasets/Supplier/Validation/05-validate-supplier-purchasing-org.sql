-- A4 / DOC 04 - Supplier / Business Partner Foundation
-- Validation 05/08: SUPPLIER_PURCHASING_ORG assignment integrity
-- Confirms ~120 org assignments (50% coverage), assignment type distribution,
-- approval status breakdown (~70% APPROVED, ~20% PENDING, ~10% REJECTED),
-- and vendor account number consistency.
-- ============================================================================
SELECT * FROM (
    SELECT 1 AS SORT_ORDER, 'ROW_COUNT' AS CHECK_ITEM, 'SUPPLIER_PURCHASING_ORG total' AS OBJECT_NAME,
           TO_NVARCHAR(COUNT(*)) AS ACTUAL_VALUE, '~120 (50% coverage)' AS EXPECTED_VALUE,
           CASE WHEN COUNT(*) BETWEEN 100 AND 140 THEN 'PASSED' ELSE 'WARNING' END AS VALIDATION_STATUS
    FROM INDUSTRIAL_DATA.SUPPLIER_PURCHASING_ORG
    UNION ALL
    SELECT 2, 'APPROVAL_STATUS_APPROVED', 'APPROVED status (~70%)',
           TO_NVARCHAR(COUNT(*)), '~84',
           CASE WHEN COUNT(*) BETWEEN 70 AND 95 THEN 'PASSED' ELSE 'WARNING' END
    FROM INDUSTRIAL_DATA.SUPPLIER_PURCHASING_ORG
    WHERE APPROVAL_STATUS = 'APPROVED'
    UNION ALL
    SELECT 3, 'APPROVAL_STATUS_PENDING', 'PENDING_APPROVAL status (~20%)',
           TO_NVARCHAR(COUNT(*)), '~24',
           CASE WHEN COUNT(*) BETWEEN 15 AND 35 THEN 'PASSED' ELSE 'WARNING' END
    FROM INDUSTRIAL_DATA.SUPPLIER_PURCHASING_ORG
    WHERE APPROVAL_STATUS = 'PENDING_APPROVAL'
    UNION ALL
    SELECT 4, 'APPROVAL_STATUS_REJECTED', 'REJECTED status (~10%)',
           TO_NVARCHAR(COUNT(*)), '~12',
           CASE WHEN COUNT(*) BETWEEN 5 AND 20 THEN 'PASSED' ELSE 'WARNING' END
    FROM INDUSTRIAL_DATA.SUPPLIER_PURCHASING_ORG
    WHERE APPROVAL_STATUS = 'REJECTED'
    UNION ALL
    SELECT 5, 'FK_SUPPLIER_PURCH_ORG_SUPPLIER', 'Invalid SUPPLIER FKs',
           TO_NVARCHAR(COUNT(*)), '0',
           CASE WHEN COUNT(*) = 0 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.SUPPLIER_PURCHASING_ORG SPO
    WHERE NOT EXISTS (SELECT 1 FROM INDUSTRIAL_DATA.SUPPLIER S WHERE S.LIFNR = SPO.LIFNR)
    UNION ALL
    SELECT 6, 'FK_SUPPLIER_PURCH_ORG_EKORG', 'Invalid PURCHASING_ORGANIZATION FKs',
           TO_NVARCHAR(COUNT(*)), '0',
           CASE WHEN COUNT(*) = 0 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.SUPPLIER_PURCHASING_ORG SPO
    WHERE NOT EXISTS (SELECT 1 FROM INDUSTRIAL_DATA.PURCHASING_ORGANIZATION PO WHERE PO.EKORG = SPO.EKORG)
    UNION ALL
    SELECT 7, 'ASSIGNMENT_TYPE_PRIMARY', 'PRIMARY assignment type',
           TO_NVARCHAR(COUNT(*)), '~40',
           'INFO'
    FROM INDUSTRIAL_DATA.SUPPLIER_PURCHASING_ORG
    WHERE ASSIGNMENT_TYPE = 'PRIMARY'
    UNION ALL
    SELECT 8, 'ASSIGNMENT_TYPE_SECONDARY', 'SECONDARY assignment type',
           TO_NVARCHAR(COUNT(*)), '~80',
           'INFO'
    FROM INDUSTRIAL_DATA.SUPPLIER_PURCHASING_ORG
    WHERE ASSIGNMENT_TYPE = 'SECONDARY'
    UNION ALL
    SELECT 9, 'VENDOR_ACCOUNT_NUMBER', 'Vendor account numbers populated (subset)',
           TO_NVARCHAR(COUNT(*)), '~40',
           'INFO'
    FROM INDUSTRIAL_DATA.SUPPLIER_PURCHASING_ORG
    WHERE VENDOR_ACCOUNT_NUMBER IS NOT NULL
)
ORDER BY SORT_ORDER, OBJECT_NAME;
