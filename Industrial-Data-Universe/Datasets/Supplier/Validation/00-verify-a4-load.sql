-- FK validation
SELECT '=== VALIDACAO DE FOREIGN KEYS ===' AS "";
SELECT
    CASE
        WHEN (SELECT COUNT(*) FROM INDUSTRIAL_DATA.SUPPLIER S
              LEFT JOIN INDUSTRIAL_DATA.SUPPLIER_TYPE ST ON S.LIFNR_TYPE = ST.SUPPLIER_TYPE_CODE
              WHERE ST.SUPPLIER_TYPE_CODE IS NULL) = 0
        THEN 'OK - Todos SUPPLIER_TYPE validos'
        ELSE 'ERRO - SUPPLIER_TYPE orfao'
    END AS "FK_SUPPLIER_TYPE";

SELECT
    CASE
        WHEN (SELECT COUNT(*) FROM INDUSTRIAL_DATA.SUPPLIER S
              LEFT JOIN INDUSTRIAL_DATA.SUPPLIER_STATUS SS ON S.LIFNR_STATUS = SS.STATUS_CODE
              WHERE SS.STATUS_CODE IS NULL) = 0
        THEN 'OK - Todos STATUS_CODE validos'
        ELSE 'ERRO - STATUS_CODE orfao'
    END AS "FK_SUPPLIER_STATUS";

SELECT
    CASE
        WHEN (SELECT COUNT(*) FROM INDUSTRIAL_DATA.SUPPLIER_PLANT SP
              LEFT JOIN INDUSTRIAL_DATA.SUPPLIER S ON SP.LIFNR = S.LIFNR
              WHERE S.LIFNR IS NULL) = 0
        THEN 'OK - Todos SUPPLIER_PLANT->SUPPLIER validos'
        ELSE 'ERRO - SUPPLIER_PLANT orfao'
    END AS "FK_SUPPLIER_PLANT_SUPPLIER";

