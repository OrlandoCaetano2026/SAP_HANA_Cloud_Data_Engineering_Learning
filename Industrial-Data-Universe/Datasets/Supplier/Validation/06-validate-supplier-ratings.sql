-- Validation 06/08: SUPPLIER_RATING historical data integrity
-- Confirms ~100 rating records across 3 time periods (2026-06, 2026-07, 2026-08),
-- score ranges 1–5 for quality/delivery/cost/overall, and period coverage.
-- ============================================================================
SELECT * FROM (
    SELECT 1 AS SORT_ORDER, 'ROW_COUNT' AS CHECK_ITEM, 'SUPPLIER_RATING total' AS OBJECT_NAME,
           TO_NVARCHAR(COUNT(*)) AS ACTUAL_VALUE, '~140 (2–3 periods per supplier)' AS EXPECTED_VALUE,
           CASE WHEN COUNT(*) BETWEEN 130 AND 160 THEN 'PASSED' ELSE 'FAILED' END AS VALIDATION_STATUS
    FROM INDUSTRIAL_DATA.SUPPLIER_RATING
    UNION ALL
    SELECT 2, 'PERIOD_2026_06', 'Records for 2026-06 (all suppliers)',
           TO_NVARCHAR(COUNT(*)), '70',
           CASE WHEN COUNT(*) = 70 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.SUPPLIER_RATING
    WHERE RATING_PERIOD = '2026-06'
    UNION ALL
    SELECT 3, 'PERIOD_2026_07', 'Records for 2026-07 (even suppliers)',
           TO_NVARCHAR(COUNT(*)), '35',
           CASE WHEN COUNT(*) BETWEEN 30 AND 40 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.SUPPLIER_RATING
    WHERE RATING_PERIOD = '2026-07'
    UNION ALL
    SELECT 4, 'PERIOD_2026_08', 'Records for 2026-08 (MOD 3=0 suppliers)',
           TO_NVARCHAR(COUNT(*)), '~23',
           CASE WHEN COUNT(*) BETWEEN 20 AND 30 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.SUPPLIER_RATING
    WHERE RATING_PERIOD = '2026-08'
    UNION ALL
    SELECT 5, 'QUALITY_SCORE_RANGE', 'Quality scores outside 1–5',
           TO_NVARCHAR(COUNT(*)), '0',
           CASE WHEN COUNT(*) = 0 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.SUPPLIER_RATING
    WHERE QUALITY_SCORE < 1 OR QUALITY_SCORE > 5
    UNION ALL
    SELECT 6, 'DELIVERY_SCORE_RANGE', 'Delivery scores outside 1–5',
           TO_NVARCHAR(COUNT(*)), '0',
           CASE WHEN COUNT(*) = 0 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.SUPPLIER_RATING
    WHERE DELIVERY_SCORE < 1 OR DELIVERY_SCORE > 5
    UNION ALL
    SELECT 7, 'COST_SCORE_RANGE', 'Cost scores outside 1–5',
           TO_NVARCHAR(COUNT(*)), '0',
           CASE WHEN COUNT(*) = 0 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.SUPPLIER_RATING
    WHERE COST_SCORE < 1 OR COST_SCORE > 5
    UNION ALL
    SELECT 8, 'OVERALL_RATING_RANGE', 'Overall ratings outside 1–5',
           TO_NVARCHAR(COUNT(*)), '0',
           CASE WHEN COUNT(*) = 0 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.SUPPLIER_RATING
    WHERE OVERALL_RATING < 1 OR OVERALL_RATING > 5
    UNION ALL
    SELECT 9, 'FK_SUPPLIER_RATING_SUPPLIER', 'Invalid SUPPLIER FKs',
           TO_NVARCHAR(COUNT(*)), '0',
           CASE WHEN COUNT(*) = 0 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.SUPPLIER_RATING SR
    WHERE NOT EXISTS (SELECT 1 FROM INDUSTRIAL_DATA.SUPPLIER S WHERE S.LIFNR = SR.LIFNR)
    UNION ALL
    SELECT 10, 'RATING_DATE_MATCH_PERIOD', 'Rating dates match period (YYYY-MM)',
           TO_NVARCHAR(SUM(CASE WHEN SUBSTRING(RATING_PERIOD, 1, 7) = SUBSTRING(CAST(RATING_DATE AS NVARCHAR), 1, 7) THEN 1 ELSE 0 END)),
           '~140 (all should match)',
           'INFO'
    FROM INDUSTRIAL_DATA.SUPPLIER_RATING
)
ORDER BY SORT_ORDER, OBJECT_NAME;
