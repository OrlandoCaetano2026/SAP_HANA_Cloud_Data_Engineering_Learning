-- Validation 03/08: SUPPLIER_PLANT cross-link integrity
-- Confirms ~320–350 plant assignments (40% coverage), valid FKs,
-- assignment type distribution (60% PRIMARY / 30% SECONDARY / 10% BACKUP),
-- and date range logic.
-- ============================================================================
SELECT * FROM (
    SELECT 1 AS SORT_ORDER, 'ROW_COUNT' AS CHECK_ITEM, 'SUPPLIER_PLANT total' AS OBJECT_NAME,
           TO_NVARCHAR(COUNT(*)) AS ACTUAL_VALUE, '~320 (40% coverage)' AS EXPECTED_VALUE,
           CASE WHEN COUNT(*) BETWEEN 300 AND 350 THEN 'PASSED' ELSE 'WARNING' END AS VALIDATION_STATUS
    FROM INDUSTRIAL_DATA.SUPPLIER_PLANT
    UNION ALL
    SELECT 2, 'ASSIGNMENT_TYPE_PRIMARY', 'PRIMARY distribution (~60%)',
           TO_NVARCHAR(COUNT(*)), '~192',
           CASE WHEN COUNT(*) BETWEEN 180 AND 210 THEN 'PASSED' ELSE 'WARNING' END
    FROM INDUSTRIAL_DATA.SUPPLIER_PLANT
    WHERE ASSIGNMENT_TYPE = 'PRIMARY'
    UNION ALL
    SELECT 3, 'ASSIGNMENT_TYPE_SECONDARY', 'SECONDARY distribution (~30%)',
           TO_NVARCHAR(COUNT(*)), '~96',
           CASE WHEN COUNT(*) BETWEEN 80 AND 110 THEN 'PASSED' ELSE 'WARNING' END
    FROM INDUSTRIAL_DATA.SUPPLIER_PLANT
    WHERE ASSIGNMENT_TYPE = 'SECONDARY'
    UNION ALL
    SELECT 4, 'ASSIGNMENT_TYPE_BACKUP', 'BACKUP distribution (~10%)',
           TO_NVARCHAR(COUNT(*)), '~32',
           CASE WHEN COUNT(*) BETWEEN 20 AND 50 THEN 'PASSED' ELSE 'WARNING' END
    FROM INDUSTRIAL_DATA.SUPPLIER_PLANT
    WHERE ASSIGNMENT_TYPE = 'BACKUP'
    UNION ALL
    SELECT 5, 'FK_SUPPLIER_PLANT_SUPPLIER', 'Invalid SUPPLIER FKs',
           TO_NVARCHAR(COUNT(*)), '0',
           CASE WHEN COUNT(*) = 0 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.SUPPLIER_PLANT SP
    WHERE NOT EXISTS (SELECT 1 FROM INDUSTRIAL_DATA.SUPPLIER S WHERE S.LIFNR = SP.LIFNR)
    UNION ALL
    SELECT 6, 'FK_SUPPLIER_PLANT_PLANT', 'Invalid PLANT FKs',
           TO_NVARCHAR(COUNT(*)), '0',
           CASE WHEN COUNT(*) = 0 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.SUPPLIER_PLANT SP
    WHERE NOT EXISTS (SELECT 1 FROM INDUSTRIAL_DATA.PLANT P WHERE P.WERKS = SP.WERKS)
    UNION ALL
    SELECT 7, 'DATE_LOGIC', 'ACTIVE_FROM > ACTIVE_TO (invalid ranges)',
           TO_NVARCHAR(COUNT(*)), '0',
           CASE WHEN COUNT(*) = 0 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.SUPPLIER_PLANT
    WHERE ACTIVE_FROM IS NOT NULL AND ACTIVE_TO IS NOT NULL AND ACTIVE_FROM > ACTIVE_TO
    UNION ALL
    SELECT 8, 'OVERRIDE_CONSISTENCY', 'Overrides without date range',
           TO_NVARCHAR(COUNT(*)), '~0 (warning)',
           'INFO'
    FROM INDUSTRIAL_DATA.SUPPLIER_PLANT
    WHERE (LEAD_TIME_PLANT_OVERRIDE IS NOT NULL OR MIN_ORDER_QTY_PLANT_OVERRIDE IS NOT NULL)
)
ORDER BY SORT_ORDER, OBJECT_NAME;
