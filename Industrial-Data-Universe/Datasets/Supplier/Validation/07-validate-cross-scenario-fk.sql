-- ============================================================================
-- A4 / DOC 04 - Supplier / Business Partner Foundation
-- Validation 07/08: cross-scenario foreign key linkage (A1→A2→A3→A4)
-- Confirms wiring between SUPPLIER (A4) ← PLANT (A1), PURCHASING_ORG (A2),
-- CURRENCY (A3). Validates path integrity: SUPPLIER → PLANT → PLANT_UNIT,
-- SUPPLIER → PURCHASING_ORG, SUPPLIER → CURRENCY.
-- ============================================================================
SELECT * FROM (
    SELECT 1 AS SORT_ORDER, 'A1_PLANT_LINKAGE' AS CHECK_ITEM, 'SUPPLIER_PLANT joins valid A1.PLANT' AS OBJECT_NAME,
           TO_NVARCHAR(COUNT(*)) AS ACTUAL_VALUE, '0 (no orphans)' AS EXPECTED_VALUE,
           CASE WHEN COUNT(*) = 0 THEN 'PASSED' ELSE 'FAILED' END AS VALIDATION_STATUS
    FROM INDUSTRIAL_DATA.SUPPLIER_PLANT SP
    LEFT JOIN INDUSTRIAL_DATA.PLANT P ON SP.WERKS = P.WERKS
    WHERE P.WERKS IS NULL
    UNION ALL
    SELECT 2, 'A2_PURCHASING_ORG_LINKAGE', 'SUPPLIER_PURCHASING_ORG joins valid A2.PURCHASING_ORGANIZATION' AS OBJECT_NAME,
           TO_NVARCHAR(COUNT(*)), '0 (no orphans)',
           CASE WHEN COUNT(*) = 0 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.SUPPLIER_PURCHASING_ORG SPO
    LEFT JOIN INDUSTRIAL_DATA.PURCHASING_ORGANIZATION PO ON SPO.EKORG = PO.EKORG
    WHERE PO.EKORG IS NULL
    UNION ALL
    SELECT 3, 'A3_CURRENCY_LINKAGE', 'SUPPLIER joins valid A3.CURRENCY',
           TO_NVARCHAR(COUNT(*)), '0 (no orphans)',
           CASE WHEN COUNT(*) = 0 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.SUPPLIER S
    LEFT JOIN INDUSTRIAL_DATA.CURRENCY C ON S.CURRENCY = C.WAERS
    WHERE C.WAERS IS NULL
    UNION ALL
    SELECT 4, 'A4_TO_A1_PLANT_UNIT', 'SUPPLIER_PLANT → PLANT → PLANT_UNIT join (3-level deep)',
           TO_NVARCHAR(COUNT(*)), '~320 (valid 3-level paths)',
           CASE WHEN COUNT(*) BETWEEN 300 AND 350 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.SUPPLIER_PLANT SP
    JOIN INDUSTRIAL_DATA.PLANT P ON SP.WERKS = P.WERKS
    JOIN INDUSTRIAL_DATA.PLANT_UNIT PU ON P.WERKS = PU.WERKS
    UNION ALL
    SELECT 5, 'A4_TO_A2_SUPPLY_SOURCE', 'SUPPLIER_PURCHASING_ORG → PURCHASING_ORG → SUPPLY_SOURCE join',
           TO_NVARCHAR(COUNT(*)), '~120 (valid 2-level paths)',
           CASE WHEN COUNT(*) BETWEEN 100 AND 140 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.SUPPLIER_PURCHASING_ORG SPO
    JOIN INDUSTRIAL_DATA.PURCHASING_ORGANIZATION PO ON SPO.EKORG = PO.EKORG
    UNION ALL
    SELECT 6, 'PAYMENT_TERMS_A4_TO_CHECK_TABLE', 'SUPPLIER → PAYMENT_TERMS join (check table)',
           TO_NVARCHAR(COUNT(*)), '70 (all suppliers linked)',
           CASE WHEN COUNT(*) = 70 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.SUPPLIER S
    JOIN INDUSTRIAL_DATA.PAYMENT_TERMS PT ON S.PAYMENT_TERMS = PT.ZTERM
    UNION ALL
    SELECT 7, 'SUPPLIER_TYPE_A4_TO_CHECK_TABLE', 'SUPPLIER → SUPPLIER_TYPE join (check table)',
           TO_NVARCHAR(COUNT(*)), '70 (all suppliers linked)',
           CASE WHEN COUNT(*) = 70 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.SUPPLIER S
    JOIN INDUSTRIAL_DATA.SUPPLIER_TYPE ST ON S.LIFNR_TYPE = ST.SUPPLIER_TYPE_CODE
    UNION ALL
    SELECT 8, 'SUPPLIER_STATUS_A4_TO_CHECK_TABLE', 'SUPPLIER → SUPPLIER_STATUS join (check table)',
           TO_NVARCHAR(COUNT(*)), '70 (all suppliers linked)',
           CASE WHEN COUNT(*) = 70 THEN 'PASSED' ELSE 'FAILED' END
    FROM INDUSTRIAL_DATA.SUPPLIER S
    JOIN INDUSTRIAL_DATA.SUPPLIER_STATUS SS ON S.LIFNR_STATUS = SS.STATUS_CODE
)
ORDER BY SORT_ORDER, OBJECT_NAME;
