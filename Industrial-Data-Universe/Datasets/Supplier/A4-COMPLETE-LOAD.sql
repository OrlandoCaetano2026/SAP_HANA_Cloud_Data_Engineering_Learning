CREATE TABLE INDUSTRIAL_DATA.SUPPLIER (
  LIFNR NVARCHAR(10) NOT NULL PRIMARY KEY,
  LIFNR_TEXT NVARCHAR(80) NOT NULL,
  LIFNR_TYPE NVARCHAR(10) NOT NULL,
  LIFNR_STATUS NVARCHAR(10) NOT NULL,
  COUNTRY NVARCHAR(3),
  CURRENCY NVARCHAR(3),
  PAYMENT_TERMS NVARCHAR(10),
  INCOTERM NVARCHAR(10),
  QUALITY_CERTIFIED NVARCHAR(1),
  LEAD_TIME_DAYS INT,
  MIN_ORDER_QTY DECIMAL(15, 2),
  FOREIGN KEY (LIFNR_TYPE) REFERENCES INDUSTRIAL_DATA.SUPPLIER_TYPE(SUPPLIER_TYPE_CODE),
  FOREIGN KEY (LIFNR_STATUS) REFERENCES INDUSTRIAL_DATA.SUPPLIER_STATUS(STATUS_CODE),
  FOREIGN KEY (PAYMENT_TERMS) REFERENCES INDUSTRIAL_DATA.PAYMENT_TERMS(ZTERM),
  FOREIGN KEY (CURRENCY) REFERENCES INDUSTRIAL_DATA.CURRENCY(WAERS),
  CHECK (LEAD_TIME_DAYS >= 1 AND LEAD_TIME_DAYS <= 120),
  CHECK (MIN_ORDER_QTY >= 0),
  CHECK (QUALITY_CERTIFIED IN ('Y', 'N'))
);

CREATE TABLE INDUSTRIAL_DATA.SUPPLIER_PLANT (
  SUPPLIER_PLANT_ID INT NOT NULL PRIMARY KEY GENERATED ALWAYS AS IDENTITY,
  LIFNR NVARCHAR(10) NOT NULL,
  WERKS NVARCHAR(4) NOT NULL,
  ASSIGNMENT_TYPE NVARCHAR(20),
  LEAD_TIME_PLANT_OVERRIDE INT,
  MIN_ORDER_QTY_PLANT_OVERRIDE DECIMAL(15, 2),
  CREATED_DATE TIMESTAMP,
  FOREIGN KEY (LIFNR) REFERENCES INDUSTRIAL_DATA.SUPPLIER(LIFNR),
  FOREIGN KEY (WERKS) REFERENCES INDUSTRIAL_DATA.PLANT(WERKS)
);

CREATE TABLE INDUSTRIAL_DATA.SUPPLIER_CONTACT (
  SUPPLIER_CONTACT_ID INT NOT NULL PRIMARY KEY GENERATED ALWAYS AS IDENTITY,
  LIFNR NVARCHAR(10) NOT NULL,
  CONTACT_NAME NVARCHAR(100) NOT NULL,
  CONTACT_TITLE NVARCHAR(50),
  CONTACT_EMAIL NVARCHAR(100),
  CONTACT_PHONE NVARCHAR(20),
  LANGUAGE NVARCHAR(2),
  CREATED_DATE TIMESTAMP,
  FOREIGN KEY (LIFNR) REFERENCES INDUSTRIAL_DATA.SUPPLIER(LIFNR)
);

CREATE TABLE INDUSTRIAL_DATA.SUPPLIER_PURCHASING_ORG (
  SUPPLIER_PO_ID INT NOT NULL PRIMARY KEY GENERATED ALWAYS AS IDENTITY,
  LIFNR NVARCHAR(10) NOT NULL,
  EKORG NVARCHAR(4) NOT NULL,
  ASSIGNMENT_TYPE NVARCHAR(20),
  APPROVAL_STATUS NVARCHAR(20),
  VENDOR_ACCOUNT_NUMBER NVARCHAR(20),
  CREATED_DATE TIMESTAMP,
  FOREIGN KEY (LIFNR) REFERENCES INDUSTRIAL_DATA.SUPPLIER(LIFNR),
  FOREIGN KEY (EKORG) REFERENCES INDUSTRIAL_DATA.PURCHASING_ORGANIZATION(EKORG)
);

CREATE TABLE INDUSTRIAL_DATA.SUPPLIER_RATING (
  SUPPLIER_RATING_ID INT NOT NULL PRIMARY KEY GENERATED ALWAYS AS IDENTITY,
  LIFNR NVARCHAR(10) NOT NULL,
  RATING_PERIOD NVARCHAR(7),
  QUALITY_SCORE INT,
  DELIVERY_SCORE INT,
  COST_SCORE INT,
  OVERALL_RATING INT,
  RATING_DATE TIMESTAMP,
  FOREIGN KEY (LIFNR) REFERENCES INDUSTRIAL_DATA.SUPPLIER(LIFNR),
  FOREIGN KEY (OVERALL_RATING) REFERENCES INDUSTRIAL_DATA.SUPPLIER_RATING_SCALE(RATING_CODE),
  CHECK (QUALITY_SCORE BETWEEN 1 AND 5),
  CHECK (DELIVERY_SCORE BETWEEN 1 AND 5),
  CHECK (COST_SCORE BETWEEN 1 AND 5),
  CHECK (OVERALL_RATING BETWEEN 1 AND 5)
);

