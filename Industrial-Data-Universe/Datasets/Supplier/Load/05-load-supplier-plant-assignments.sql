-- Script 05/08 (Load): create and populate SUPPLIER_PLANT assignments
-- Target schema : INDUSTRIAL_DATA
-- Purpose       : associate suppliers to plants (not every supplier is available
--                 in every plant). Coverage: ~40–50% (320–350 rows out of 1400).
-- ============================================================================

DROP TABLE INDUSTRIAL_DATA.SUPPLIER_PLANT;

CREATE COLUMN TABLE INDUSTRIAL_DATA.SUPPLIER_PLANT (
    LIFNR                   NVARCHAR(10) NOT NULL,
    WERKS                   NVARCHAR(4)  NOT NULL,
    ASSIGNMENT_TYPE         NVARCHAR(20) NOT NULL,
    ACTIVE_FROM             DATE         NOT NULL,
    ACTIVE_TO               DATE,
    LEAD_TIME_PLANT_OVERRIDE INTEGER,
    MIN_ORDER_QTY_PLANT_OVERRIDE DECIMAL(13,3),
    PRIMARY KEY (LIFNR, WERKS),
    CONSTRAINT FK_SUPPLIER_PLANT_SUPPLIER
        FOREIGN KEY (LIFNR) REFERENCES INDUSTRIAL_DATA.SUPPLIER (LIFNR),
    CONSTRAINT FK_SUPPLIER_PLANT_PLANT
        FOREIGN KEY (WERKS) REFERENCES INDUSTRIAL_DATA.PLANT (WERKS),
    CONSTRAINT CHK_SUPPLIER_PLANT_TYPE CHECK (ASSIGNMENT_TYPE IN ('PRIMARY','SECONDARY','BACKUP')),
    CONSTRAINT CHK_SUPPLIER_PLANT_DATES CHECK (ACTIVE_FROM <= ACTIVE_TO OR ACTIVE_TO IS NULL),
    CONSTRAINT CHK_SUPPLIER_PLANT_LT CHECK (LEAD_TIME_PLANT_OVERRIDE IS NULL OR LEAD_TIME_PLANT_OVERRIDE BETWEEN 1 AND 180),
    CONSTRAINT CHK_SUPPLIER_PLANT_MOQ CHECK (MIN_ORDER_QTY_PLANT_OVERRIDE IS NULL OR MIN_ORDER_QTY_PLANT_OVERRIDE > 0)
);

-- Populate SUPPLIER_PLANT: cross join suppliers and plants, filter to ~40% coverage ---
INSERT INTO INDUSTRIAL_DATA.SUPPLIER_PLANT
    (LIFNR, WERKS, ASSIGNMENT_TYPE, ACTIVE_FROM, ACTIVE_TO, LEAD_TIME_PLANT_OVERRIDE, MIN_ORDER_QTY_PLANT_OVERRIDE)
SELECT
    S.LIFNR,
    P.WERKS,
    CASE MOD(CAST(SUBSTRING(S.LIFNR, 5) AS INT) * 7 + CAST(P.WERKS AS INT), 10)
        WHEN 0 THEN 'SECONDARY'
        WHEN 1 THEN 'BACKUP'
        ELSE 'PRIMARY'
    END AS ASSIGNMENT_TYPE,
    DATE '2026-01-01' AS ACTIVE_FROM,
    NULL AS ACTIVE_TO,
    CASE MOD(CAST(SUBSTRING(S.LIFNR, 5) AS INT) + CAST(P.WERKS AS INT), 3)
        WHEN 0 THEN NULL
        WHEN 1 THEN 14 + MOD(CAST(SUBSTRING(S.LIFNR, 5) AS INT) * 11, 30)
        ELSE 21 + MOD(CAST(P.WERKS AS INT) * 13, 30)
    END AS LEAD_TIME_PLANT_OVERRIDE,
    CASE MOD(CAST(SUBSTRING(S.LIFNR, 5) AS INT) * 3 + CAST(P.WERKS AS INT), 7)
        WHEN 0 THEN NULL
        WHEN 1 THEN 75.00
        WHEN 2 THEN 150.00
        WHEN 3 THEN 50.00
        ELSE NULL
    END AS MIN_ORDER_QTY_PLANT_OVERRIDE
FROM INDUSTRIAL_DATA.SUPPLIER S
CROSS JOIN INDUSTRIAL_DATA.PLANT P
WHERE MOD(CAST(SUBSTRING(S.LIFNR, 5) AS INT) * CAST(P.WERKS AS INT), 5) IN (0, 1, 2);

COMMIT;
