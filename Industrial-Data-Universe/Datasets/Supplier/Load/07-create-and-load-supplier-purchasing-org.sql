-- Script 07/08 (Load): create and populate SUPPLIER_PURCHASING_ORG assignments
-- Target schema : INDUSTRIAL_DATA
-- Purpose       : associate suppliers to purchasing organizations (A2 EKORG).
--                 Coverage: ~50% (not every supplier in every org).
-- ============================================================================

DROP TABLE INDUSTRIAL_DATA.SUPPLIER_PURCHASING_ORG;

CREATE COLUMN TABLE INDUSTRIAL_DATA.SUPPLIER_PURCHASING_ORG (
    LIFNR                   NVARCHAR(10) NOT NULL,
    EKORG                   NVARCHAR(4)  NOT NULL,
    ASSIGNMENT_TYPE         NVARCHAR(20) NOT NULL,
    APPROVAL_STATUS         NVARCHAR(20) NOT NULL,
    VENDOR_ACCOUNT_NUMBER   NVARCHAR(30),
    PRIMARY KEY (LIFNR, EKORG),
    CONSTRAINT FK_SUPPLIER_PURCH_ORG_SUPPLIER
        FOREIGN KEY (LIFNR) REFERENCES INDUSTRIAL_DATA.SUPPLIER (LIFNR),
    CONSTRAINT FK_SUPPLIER_PURCH_ORG_PURCH_ORG
        FOREIGN KEY (EKORG) REFERENCES INDUSTRIAL_DATA.PURCHASING_ORGANIZATION (EKORG),
    CONSTRAINT CHK_SUPPLIER_PURCH_ORG_TYPE CHECK (ASSIGNMENT_TYPE IN ('PRIMARY','SECONDARY')),
    CONSTRAINT CHK_SUPPLIER_PURCH_ORG_APPROVAL CHECK (APPROVAL_STATUS IN ('APPROVED','PENDING_APPROVAL','REJECTED'))
);

-- Populate SUPPLIER_PURCHASING_ORG: selective cross-join (50% coverage) -------
INSERT INTO INDUSTRIAL_DATA.SUPPLIER_PURCHASING_ORG
    (LIFNR, EKORG, ASSIGNMENT_TYPE, APPROVAL_STATUS, VENDOR_ACCOUNT_NUMBER)
SELECT
    S.LIFNR,
    PO.EKORG,
    CASE MOD(CAST(SUBSTRING(S.LIFNR, 5) AS INT) * 11 + CAST(REPLACE(PO.EKORG, 'P', '') AS INT), 3)
        WHEN 0 THEN 'SECONDARY'
        ELSE 'PRIMARY'
    END AS ASSIGNMENT_TYPE,
    CASE MOD(CAST(SUBSTRING(S.LIFNR, 5) AS INT) * 13 + CAST(REPLACE(PO.EKORG, 'P', '') AS INT), 10)
        WHEN 0 THEN 'REJECTED'
        WHEN 1 THEN 'PENDING_APPROVAL'
        ELSE 'APPROVED'
    END AS APPROVAL_STATUS,
    CASE WHEN MOD(CAST(SUBSTRING(S.LIFNR, 5) AS INT) + CAST(REPLACE(PO.EKORG, 'P', '') AS INT), 3) = 0
         THEN 'ACC-' || LPAD(CAST(CAST(SUBSTRING(S.LIFNR, 5) AS INT) * CAST(REPLACE(PO.EKORG, 'P', '') AS INT) AS NVARCHAR), 5, '0')
         ELSE NULL
    END AS VENDOR_ACCOUNT_NUMBER
FROM INDUSTRIAL_DATA.SUPPLIER S
CROSS JOIN INDUSTRIAL_DATA.PURCHASING_ORGANIZATION PO
WHERE MOD(CAST(SUBSTRING(S.LIFNR, 5) AS INT) * CAST(REPLACE(PO.EKORG, 'P', '') AS INT), 2) = 0;

COMMIT;
